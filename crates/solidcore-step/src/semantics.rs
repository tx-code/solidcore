/// Checked source ownership facts, never a geometric validity or material proof.
#[derive(Clone, Debug, Default, Serialize)]
pub struct Part {
    /// Source roles in the same deterministic order as the C++ checker.
    pub roles: Vec<Role>,
    /// All proven source property links, including shared representations/items.
    pub property_attachments: Vec<PropertyAttachment>,
    /// General-scope faces whose ordinary bounds require later region evidence.
    pub deferred_region_faces: Vec<usize>,
    /// MaterialSolid/OpenSurfaceModel/ClosedSurfaceModel: original source claim.
    pub shape_role: String,
    /// Original APD status STRING.
    pub apd_status: String,
    /// Original APD schema claim, never used to infer the HEADER edition.
    pub apd_schema_claim: String,
    /// Exact APD INTEGER lexeme.
    pub apd_year: String,
    /// A real source APD exists; strict mode never fabricates one.
    pub application_protocol_present: bool,
}

/// Source-check status; no variant grants native model acceptance.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
pub enum Status {
    /// Exactly the requested type/unit checkpoint passed.
    Checked,
    /// Requested source checks completed while original errors/assumptions remain.
    CheckedWithDiagnostics,
    /// Requested physical length scale remains deferred (conversion-based unit).
    Deferred,
    /// A source declaration or necessary unit predicate failed.
    Rejected,
    /// Outside the selected fixed source subset.
    Unsupported,
    /// Visit budget or exact arithmetic capacity exceeded.
    ResourceLimit,
    /// Source syntax/index/reference inspection did not succeed.
    SourceFailure,
    /// The caller selected an absent or inappropriate context.
    InvalidRequest,
    /// Internal descriptor/binding invariant failed; not a source-invalid verdict.
    InfrastructureFailure,
}

/// Original source diagnostic plus typed provenance and classification.
#[derive(Clone, Debug, Serialize)]
pub struct Diagnostic {
    /// Stable source identity, stage, spans, owner and parameter path.
    pub source: SourceDiagnostic,
    /// `SourceInvalid` / `ProfileUnsupported` / `ResourceLimit` / `SourceInspectionFailure`.
    pub classification: String,
    /// Source attribute name, when present.
    pub field: String,
    /// Original declaring type, even for inherited/redeclared fields.
    pub declared_in: String,
    /// Effective declared type after explicit narrowing.
    pub declared_type: String,
    /// Expected source requirement.
    pub expected: String,
    /// Observed original kind/lexeme, never a repaired value.
    pub actual: String,
    /// Fixed source artifact/clause or explicit project restriction.
    pub responsibility: String,
}

/// Original HEADER identity; numeric OID arcs are never normalized to integers.
#[derive(Clone, Debug, Serialize)]
pub struct SchemaIdentifier {
    /// Complete original decoded schema literal.
    pub literal: String,
    /// Parsed schema name.
    pub name: String,
    /// Original numeric arc strings, including any leading zeros.
    pub oid: Vec<String>,
    /// Original STRING token span.
    pub span: crate::Span,
    /// Recognized protocol family, independently of implemented support.
    pub protocol: String,
    /// Malformed/UnknownName/NameOnly/LegacyAlias/UnregisteredVersion/RegisteredVersion.
    #[serde(rename = "match")]
    pub matched: String,
    /// Exact known registry identity, empty when unregistered.
    pub registry_id: String,
}

