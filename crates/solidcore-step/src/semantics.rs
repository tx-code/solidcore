/// Explicit request budgets for source checking, not geometric tolerances.
#[derive(Clone, Copy, Debug, Serialize)]
pub struct Limits {
    /// Maximum dependency/field visits; ceiling is 10 million as in C++.
    pub dependency_visits: usize,
    /// Shared capacity for original metadata and schema-interpretation diagnostics.
    pub preserved_diagnostics: usize,
}
impl Limits {
    /// Test preset inherited from the C++ source checker, never a production default.
    pub const fn fixtures() -> Self {
        Self {
            dependency_visits: 1_000_000,
            preserved_diagnostics: 1024,
        }
    }
}

/// Explicit source-error policy; no geometry is repaired or silently discarded.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq, Serialize)]
pub enum SourcePolicy {
    /// Every original source error remains fatal.
    #[default]
    Strict,
    /// Retain eligible nongeometric errors only after the final ownership proof.
    PreserveNonGeometric,
}

/// Caller-selected unverified schema interpretation; never inferred from APD text.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq, Serialize)]
pub enum SchemaInterpretation {
    /// Only registered/default source bindings are selected.
    #[default]
    DeclaredOnly,
    /// Exactly the unregistered eight-arc AP214 literal selects the fixed 2010 subset.
    UnregisteredAp214As2010,
    /// Exactly bare `AUTOMOTIVE_DESIGN` selects that same fixed implementation.
    Ap214NameOnlyAs2010,
}
fn is_default<T: Default + PartialEq>(value: &T) -> bool {
    value == &T::default()
}

/// Profile selection is separate from interpretation of any source parameters.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq, Serialize)]
pub enum GeometryScope {
    /// Preserve the original AP203 planar source catalog.
    #[default]
    ExplicitOuterBounds,
    /// Explicitly select the corresponding general source catalog where implemented.
    GeneralBrep,
}

/// Caller-selected checkpoint. No context is guessed from filenames or units.
#[derive(Clone, Debug, Default)]
pub struct Options {
    /// Explicit nongeometric policy; enables the complete source phase sequence.
    pub source_policy: SourcePolicy,
    /// Explicit implementation assumption, requiring general interoperability.
    pub schema_interpretation: SchemaInterpretation,
    /// Select the same source catalog policy as C++.
    pub geometry_scope: GeometryScope,
    /// Canonical source ID of the physical context to check, if requested.
    /// Without ownership mode this does not prove selected-part ownership; with
    /// ownership mode it must agree with the context selected by the proved chain.
    pub physical_context: Option<String>,
    /// Run the strict selected-part and dependency-closure checkpoint. Its unit
    /// context comes from the proved source chain; geometry/native remain unrun.
    pub check_part_and_closure: bool,
    /// Run the fixed source geometry prerequisites before ownership. This is
    /// source parameter/dependency checking, not geometric/native acceptance.
    pub check_geometry_dependencies: bool,
}

