struct Data {
    qualification: interop::Qualification,
    source: SourceSnapshot,
    catalog: &'static catalog::Catalog,
    profile: Profile,
    types: Vec<catalog::Membership>,
    populations: Vec<Vec<usize>>,
    attributes: Vec<Vec<Attribute>>,
    units: Units,
    part: Option<Part>,
    representation_use: Option<Vec<bool>>,
}

/// Owning immutable typed source snapshot. It never owns a native model.
#[derive(Clone)]
pub struct Snapshot {
    data: Arc<Data>,
}
impl Snapshot {
    /// Original source policy of this immutable qualified snapshot.
    pub fn source_policy(&self) -> SourcePolicy {
        self.data.qualification.policy
    }
    /// Exact source geometry scope requested for this immutable snapshot.
    pub fn geometry_scope(&self) -> GeometryScope {
        self.data.qualification.scope
    }
    /// Applied schema assumption, independent of resettable outcome annotations.
    pub fn applied_interpretation(&self) -> SchemaInterpretation {
        self.data.qualification.applied
    }
    /// Original unsupported binding diagnostic preserved for an applied assumption.
    pub fn interpretation_diagnostics(&self) -> &[Diagnostic] {
        &self.data.qualification.interpretation
    }
    /// Original source errors approved by the final nongeometric exclusion proof.
    pub fn preserved_diagnostics(&self) -> &[Diagnostic] {
        &self.data.qualification.preserved
    }
    /// Proven nongeometric residue; these records never become part/geometry roots.
    pub fn unattached_non_geometric(&self) -> &[usize] {
        &self.data.qualification.unattached
    }
    /// Proved source part facts, absent when the ownership checkpoint was unrun.
    pub fn part_definition(&self) -> Option<&Part> {
        self.data.part.as_ref()
    }
    /// RI-filtered representation-use closure, distinct from broad ownership.
    /// Returns `None` for an unrun checkpoint or out-of-range source record.
    pub fn used_by_representation(&self, record: usize) -> Option<bool> {
        let used = *self.data.representation_use.as_ref()?.get(record)?;
        Some(self.is_a(record, "REPRESENTATION_ITEM")? && used)
    }
    /// Registered inverse role as indices into the original source references.
    /// Repeated LIST/BAG uses remain separate occurrences in source order.
    /// Unknown target/type/role returns `None`, rather than a proved empty use set.
    pub fn used_in(&self, target_id: &str, owner_type: &str, field: &str) -> Option<Vec<usize>> {
        let catalog = self.data.catalog;
        let type_id = catalog.find(owner_type)?;
        let declared =
            catalog
                .declarations
                .get(type_id)?
                .flattened
                .iter()
                .any(|(origin, local)| {
                    catalog
                        .declarations
                        .get(*origin)
                        .and_then(|d| d.fields.get(*local))
                        .is_some_and(|f| f.name == field)
                });
        if !declared {
            return None;
        }
        self.data.source.find(target_id)?;
        let mut uses = Vec::new();
        for index in self.data.source.incoming(target_id) {
            let reference = self.data.source.references().get(*index)?;
            let parameter = reference.parameter_path.first()?.checked_sub(1)?;
            if self.is_a(reference.record_index, owner_type)?
                && self
                    .data
                    .attributes
                    .get(reference.record_index)?
                    .iter()
                    .any(|a| {
                        a.component == reference.component_index
                            && a.parameter == parameter
                            && a.name == field
                    })
            {
                uses.push(*index);
            }
        }
        Some(uses)
    }
    /// Original complete immutable source graph, retained without copying values.
    pub fn source(&self) -> &SourceSnapshot {
        &self.data.source
    }
    /// Resolve a source reference value through the original immutable index.
    /// Aggregate members use the same identity interpretation as bound scalar
    /// fields; a non-reference or missing identity is never a fabricated target.
    pub fn reference_target(&self, value: &Value) -> Option<usize> {
        (value.kind == crate::ValueKind::Reference).then_some(())?;
        self.data.source.data.index.get(&value.text).copied()
    }
    /// Selected fixed profile.
    pub fn profile(&self) -> &Profile {
        &self.data.profile
    }
    /// Exact unit metadata actually checked.
    pub fn units(&self) -> &Units {
        &self.data.units
    }
    /// Registered declarations in stable catalog order.
    pub fn registered_types(&self) -> impl Iterator<Item = &'static str> {
        self.data.catalog.declarations.iter().map(|d| d.name)
    }
    /// Source-local instances of a known type; unknown differs from a proved empty set.
    pub fn instances(&self, name: &str) -> Option<&[usize]> {
        self.data
            .catalog
            .find(name)
            .and_then(|id| self.data.populations.get(id))
            .map(Vec::as_slice)
    }
    /// Source membership, with unknown type/index distinguished from false.
    pub fn is_a(&self, record: usize, name: &str) -> Option<bool> {
        let id = self.data.catalog.find(name)?;
        Some(self.data.types.get(record)?.contains(id))
    }
    /// Stable source type memberships for one record.
    pub fn types_of(&self, record: usize) -> Option<Vec<&'static str>> {
        let bits = *self.data.types.get(record)?;
        Some(
            self.data
                .catalog
                .declarations
                .iter()
                .enumerate()
                .filter_map(|(i, d)| bits.contains(i).then_some(d.name))
                .collect(),
        )
    }
    /// Source-ordered bindings; values still belong to the original source graph.
    pub fn attributes(&self, record: usize) -> Option<&[Attribute]> {
        self.data.attributes.get(record).map(Vec::as_slice)
    }
    /// Unique named field. Qualify an inherited name by its original declaring type.
    pub fn field(&self, record: usize, declared_in: Option<&str>, name: &str) -> Option<FieldView> {
        let attrs = self.data.attributes.get(record)?;
        let mut found = attrs
            .iter()
            .enumerate()
            .filter(|(_, a)| a.name == name && declared_in.is_none_or(|d| d == a.declared_in));
        let (attribute, _) = found.next()?;
        if found.next().is_some() {
            return None;
        }
        Some(FieldView {
            data: Arc::clone(&self.data),
            record,
            attribute,
        })
    }
}

/// Owning field handle; remains valid after its original outcome/snapshot is dropped.
pub struct FieldView {
    data: Arc<Data>,
    record: usize,
    attribute: usize,
}
impl FieldView {
    /// Declaration and source slot identity.
    pub fn declaration(&self) -> Option<&Attribute> {
        self.data.attributes.get(self.record)?.get(self.attribute)
    }
    /// Exact original value, borrowed from this handle's owning source snapshot.
    pub fn value(&self) -> Option<&Value> {
        let a = self.declaration()?;
        self.data
            .source
            .records()
            .get(self.record)?
            .components
            .get(a.component)?
            .parameters
            .get(a.parameter)
    }
    /// Canonical target's source index, only for a bound reference field.
    pub fn reference_target(&self) -> Option<usize> {
        let v = self.value()?;
        (v.kind == crate::ValueKind::Reference).then_some(())?;
        self.data.source.data.index.get(&v.text).copied()
    }
}

/// Checkpoint outcome; failure never publishes a partially bound snapshot.
pub struct Outcome {
    qualification: interop::Qualification,
    // Bind even failed checkpoints to their exact immutable source capture;
    // compiling a report against another request is an infrastructure error.
    source_capture: Option<Arc<[u8]>>,
    check_part_and_closure: bool,
    check_geometry_dependencies: bool,
    /// Final checkpoint status, not full AP/native acceptance.
    pub status: Status,
    /// Completed owning typed source, absent on any requested-check failure.
    pub snapshot: Option<Snapshot>,
    /// HEADER binding observations, retained on failure.
    pub schema_selection: Option<SchemaSelection>,
    /// Binding progress.
    pub binding: &'static str,
    /// Type/field progress.
    pub types: &'static str,
    /// Necessary dimensional dependency progress; P0 deliberately keeps `NotRun`.
    pub unit_dependencies: &'static str,
    /// Fixed source geometry parameter/dependency progress; P0 retains `NotRun`.
    pub geometry_dependencies: &'static str,
    /// Actual attempted source geometry prerequisites and counters.
    pub geometry_dependency_checks: GeometryChecks,
    /// Requested physical context progress; `NotRun` without an explicit context.
    pub si_units: &'static str,
    /// Selected-part/closure progress, including general source-region deferral.
    pub part: &'static str,
    /// Final approval progress; remains `NotRun` on strict or failed earlier stages.
    pub interoperability: &'static str,
    /// Actual property links attempted before any failure.
    pub property_attachment_checks: usize,
    /// Actual traversal visits, including a visit that exceeded its budget.
    pub dependency_visits: usize,
    /// Actual unit prerequisite counters.
    pub unit_dependency_checks: UnitChecks,
    /// Explicit request limits.
    pub limits: Limits,
    /// Fatal original source diagnostics with full typed provenance.
    pub diagnostics: Vec<Diagnostic>,
}

impl Outcome {
    pub(crate) fn captured_owner(&self) -> Option<Arc<[u8]>> {
        self.source_capture.clone()
    }
    /// Requested source policy, bound to the immutable successful snapshot.
    pub fn source_policy(&self) -> SourcePolicy {
        self.snapshot
            .as_ref()
            .map_or(self.qualification.policy, Snapshot::source_policy)
    }
    /// Exact source geometry scope, not inferred from the catalog name or role.
    pub fn geometry_scope(&self) -> GeometryScope {
        self.snapshot
            .as_ref()
            .map_or(self.qualification.scope, Snapshot::geometry_scope)
    }
    /// Requested schema assumption; may be unapplied if normal binding succeeds.
    pub fn requested_interpretation(&self) -> SchemaInterpretation {
        self.qualification.requested
    }
    /// Actual immutable source qualification, even if mutable notices are cleared.
    pub fn applied_interpretation(&self) -> SchemaInterpretation {
        self.snapshot
            .as_ref()
            .map_or(self.qualification.applied, Snapshot::applied_interpretation)
    }
    /// Original binding refusals; failure retains interpretations already applied.
    pub fn interpretation_diagnostics(&self) -> &[Diagnostic] {
        self.snapshot.as_ref().map_or(
            &self.qualification.interpretation,
            Snapshot::interpretation_diagnostics,
        )
    }
    /// Approved source errors, empty until the complete requested proof succeeds.
    pub fn preserved_diagnostics(&self) -> &[Diagnostic] {
        self.snapshot.as_ref().map_or(
            &self.qualification.preserved,
            Snapshot::preserved_diagnostics,
        )
    }
    /// Proven residue identities, without manufacturing source ownership roles.
    pub fn unattached_non_geometric(&self) -> &[usize] {
        self.snapshot
            .as_ref()
            .map_or(&[], Snapshot::unattached_non_geometric)
    }
}

/// Check the explicitly selected source checkpoint with strict source behavior.
///
/// Types/units mode checks only the requested context. Part/closure mode first
/// proves the source chain and closure, then checks its actual context.
/// Strict shortened modes do not grant interoperability. Explicit nongeometric
/// policy runs all source phases and the final exclusion proof. No mode constructs `BRep`.
pub fn check(source: &SourceOutcome, limits: Limits, options: &Options) -> Outcome {
    checker::check(source, limits, options)
}

/// Fingerprint of the complete fixed C++ transport descriptor export used by Rust.
pub fn catalog_source_sha256() -> &'static str {
    generated::SOURCE_SHA256
}

/// Semantic report could not be compiled; callers must publish no partial JSON.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ReportError {
    /// Supplied source inspection belongs to another request/capture.
    SourceMismatch,
    /// Bounded JSON compilation failed.
    Output(crate::report::Error),
}

/// Compile the source-bound selected-checkpoint report within the source budget.
/// Every unrun stage remains explicit. Private source data is included; the
/// report inherits the input's confidentiality policy.
pub fn compile_report(source: &SourceOutcome, outcome: &Outcome) -> Result<Vec<u8>, ReportError> {
    report::compile(source, outcome)
}
